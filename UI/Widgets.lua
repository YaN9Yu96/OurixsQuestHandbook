-- ---- Brand icon --------------------------------------------------------------
-- One texture per call site, so each title bar / button owns its own texture object.
-- `trim` zooms slightly into the artwork (the source PNG keeps a few percent of dark
-- margin) so the scroll + chain silhouette fills the requested square instead of
-- shrinking inside its own padding. Pass trim = 0 to use the raw image.
W.BRAND_ICON = BRAND_ICON
function W.BrandIcon(parent, size, layer, trim)
    local t = parent:CreateTexture(nil, layer or "ARTWORK")
    local s = size or 20
    t:SetSize(s, s)
    t:SetTexture(BRAND_ICON)
    local k = trim or 0.04
    if k > 0 then pcall(t.SetTexCoord, t, k, 1 - k, k, 1 - k) end
    return t
end
