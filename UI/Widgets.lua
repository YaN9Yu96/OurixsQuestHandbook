local _, ns = ...

-- Self-contained native widgets, ported from the proven technique used by modern
-- WoW settings panels (PlateSCT-style): every fill is a Shape -- four corner
-- textures plus three solid strips -- tinted with vertex colours, with an optional
-- 1px ring. Flat fills, no gradients, no shadows, no emboss. A single soft warm-gold
-- accent (#d9ae5f) is used for TEXT / RING / active controls only.
--
-- Assets used (all safe):
--   * Interface\Buttons\WHITE8X8  -> Blizzard's own 1x1 white texture (strips / solids)
--   * Interface/AddOns/OurixsQuestHandbook/Media/Round.png -> OUR OWN generated corner
--     texture (a centred white circle; each quadrant is one quarter-disk). We do NOT
--     borrow any file from another addon; this Round.png was generated by this project.
--   * SetColorTexture for hairline borders/lines (no texture needed).
--   * Blizzard's DialogBox / QuestFrame textures are used ONLY for the NPC companion
--     panel, which is intentionally a native Blizzard DialogBox (core game assets).
local W = {}
ns.Widgets = W

-- Shared white texture: Blizzard's built-in (always present, never another addon).
local WHITE = "Interface\\Buttons\\WHITE8X8"
-- Our own generated corner texture (NOT copied from anywhere).
local ROUND = "Interface/AddOns/OurixsQuestHandbook/Media/Round.png"
-- The addon's own 512x512 brand icon (scroll + chain links), used by the addon list,
-- the window title bars and the minimap button. PNG, not TGA: this client refuses to
-- load TGA textures.
local BRAND_ICON = "Interface/AddOns/OurixsQuestHandbook/Media/Icon.png"
local QUEST_HIGHLIGHT = "Interface\\QuestFrame\\UI-QuestTitleHighlight"
local DIALOG_BG  = "Interface\\DialogFrame\\UI-DialogBox-Background"
local DIALOG_EDGE = "Interface\\DialogFrame\\UI-DialogBox-Border"
local DIALOG_HEADER = "Interface\\DialogFrame\\UI-DialogBox-Header"

-- PlateSCT-style: keep Blizzard's text shadow off so labels read crisp, not heavy.
W.TEXT_SHADOW = false

-- ---- Warm "Midnight" layered palette (near-black charcoal + soft gold accent) ----
-- These values are intentionally the same family as modern settings panels; the
-- accent (#d9ae5f) is TEXT / RING only, never a large fill.
local A = 0.97
local L0 = { 0.071, 0.063, 0.051, A }   -- window glass (deepest, warm)
local L1 = { 0.090, 0.078, 0.059, A }   -- section / card fill
local L2 = { 0.106, 0.094, 0.075, 1 }   -- list / button base (field)
local L3 = { 0.133, 0.118, 0.094, A }   -- hover lightening
local L4 = { 0.169, 0.145, 0.106, A }   -- selected / raised
local DIV = { 0.141, 0.122, 0.094, 1 }  -- dividers / separators
local ACCENT = { 0.851, 0.682, 0.373 }  -- #d9ae5f soft warm gold (TEXT / RING only)
local GOLD   = { 0.851, 0.682, 0.373 }  -- data-source tag (same soft gold)
local CTRL_BORDER = { 0.180, 0.157, 0.122 } -- control edge (warm, slightly lit)
local CARD_BORDER = { 0.180, 0.157, 0.122, 0.9 } -- 1px warm edge ring (no glow)

local function Blend(a, b, t)
    return { a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t, a[3] + (b[3] - a[3]) * t, 1 }
end

W.Theme = {
    bg        = { L0[1], L0[2], L0[3], A },   -- window glass (deepest)
    panel     = { L2[1], L2[2], L2[3], 1 },   -- list / section background
    panelAlt  = { L2[1], L2[2], L2[3], 1 },   -- buttons / inputs
    top       = { L1[1], L1[2], L1[3], A },   -- top / foot bars, group headers
    row       = { L2[1], L2[2], L2[3], 1 },   -- quest row base
    rowHover  = { L3[1], L3[2], L3[3], A },   -- hover lightening
    rowSel    = Blend(L2, ACCENT, 0.18),      -- selected row: subtle warm tint
    line      = { DIV[1], DIV[2], DIV[3], 1 },-- dividers / separators
    border    = { CTRL_BORDER[1], CTRL_BORDER[2], CTRL_BORDER[3], 0.7 },
    accent    = ACCENT,                       -- gold: TEXT / RING only
    accentDim = Blend(L3, ACCENT, 0.45),     -- chain trunk / arm lines
    gold      = GOLD,                         -- secondary data-source tag
    text      = { 0.929, 0.902, 0.847 },     -- warm off-white
    muted     = { 0.639, 0.604, 0.541 },     -- body / meta text
    card      = { L1[1], L1[2], L1[3], A },   -- chain card fill
}

-- ---- Rounded shapes (ported from the proven PlateSCT technique) -----------------

-- A shape is four quarter-circle corners and three strips, tinted with vertex colors.
-- Every fill is opaque, so the strips may abut without visible seams.
local CORNERS = {
    { "TOPLEFT",     1, -1, 0,    0.5, 0,    0.5 },
    { "TOPRIGHT",   -1, -1, 0.5,  1,   0,    0.5 },
    { "BOTTOMRIGHT", -1,  1, 0.5,  1,   0.5,  1   },
    { "BOTTOMLEFT",   1,  1, 0,    0.5, 0.5,  1   },
}

local function NoSnap(texture)
    if texture.SetSnapToPixelGrid then texture:SetSnapToPixelGrid(false) end
    if texture.SetTexelSnappingBias then texture:SetTexelSnappingBias(0) end
end

local function NewShape(frame, sublevel)
    local shape = { frame = frame, parts = {} }
    for i = 1, 7 do
        local texture = frame:CreateTexture(nil, "BACKGROUND", nil, sublevel)
        NoSnap(texture)
        shape.parts[i] = texture
    end
    return shape
end

local function LayoutShape(shape, radius, inset, square)
    local key = radius .. ":" .. inset .. ":" .. (square or "")
    if shape.key == key then return end
    shape.key = key
    local frame, parts = shape.frame, shape.parts
    for i, spec in ipairs(CORNERS) do
        local corner = parts[i]
        corner:ClearAllPoints()
        corner:SetPoint(spec[1], frame, spec[1], spec[2] * inset, spec[3] * inset)
        corner:SetSize(radius, radius)
        if square and square:find(tostring(i), 1, true) then
            corner:SetTexture(WHITE); corner:SetTexCoord(0, 1, 0, 1)
        else
            corner:SetTexture(ROUND); corner:SetTexCoord(spec[4], spec[5], spec[6], spec[7])
        end
    end
    local top, middle, bottom = parts[5], parts[6], parts[7]
    for _, strip in ipairs({ top, middle, bottom }) do
        strip:SetTexture(WHITE); strip:ClearAllPoints()
    end
    top:SetPoint("TOPLEFT", frame, "TOPLEFT", inset + radius, -inset)
    top:SetPoint("TOPRIGHT", frame, "TOPRIGHT", -inset - radius, -inset)
    top:SetHeight(math.max(radius, 0.01))
    bottom:SetPoint("BOTTOMLEFT", frame, "BOTTOMLEFT", inset + radius, inset)
    bottom:SetPoint("BOTTOMRIGHT", frame, "BOTTOMRIGHT", -inset - radius, inset)
    bottom:SetHeight(math.max(radius, 0.01))
    middle:SetPoint("TOPLEFT", frame, "TOPLEFT", inset, -inset - radius)
    middle:SetPoint("BOTTOMRIGHT", frame, "BOTTOMRIGHT", -inset, inset + radius)
    shape.rounded = radius > 0
end

local function ColorShape(shape, color)
    for _, part in ipairs(shape.parts) do
        part:SetVertexColor(color[1], color[2], color[3], color[4] or 1)
        part:SetShown(shape.rounded or part == shape.parts[6])
    end
end

local function HideShape(shape)
    if not shape then return end
    for _, part in ipairs(shape.parts) do part:Hide() end
end

-- Paint a rounded fill, with an optional 1px ring. `square` lists corners (1 TL, 2 TR,
-- 3 BR, 4 BL) that stay square where a panel meets the window edge.
function W.Paint(frame, fill, radius, ring, square)
    radius = radius or 8
    frame.optionsFillShape = frame.optionsFillShape or NewShape(frame, -6)
    if ring then
        frame.optionsRingShape = frame.optionsRingShape or NewShape(frame, -7)
        LayoutShape(frame.optionsRingShape, radius, 0, square)
        ColorShape(frame.optionsRingShape, ring)
        LayoutShape(frame.optionsFillShape, math.max(0, radius - 1), 1, square)
    else
        HideShape(frame.optionsRingShape)
        LayoutShape(frame.optionsFillShape, radius, 0, square)
    end
    ColorShape(frame.optionsFillShape, fill)
    frame.optionsFill = fill
end

-- Recolour a painted frame (used by hover / selected state changes).
function W.Tint(frame, color)
    if frame.optionsFillShape then ColorShape(frame.optionsFillShape, color) end
end

-- ---- Public widget API -------------------------------------------------------

local function solid(parent, r, g, b, a, layer)
    local t = parent:CreateTexture(nil, layer or "BACKGROUND")
    t:SetAllPoints(parent)
    t:SetColorTexture(r, g, b, a or 1)
    return t
end

function W.Frame(name, parent)
    local ok, f = pcall(CreateFrame, "Frame", name, parent, "BackdropTemplate")
    if ok and f then return f end
    return CreateFrame("Frame", name, parent)
end

function W.Font(parent, template, layer)
    local fs = parent:CreateFontString(nil, layer or "OVERLAY", template or "GameFontNormal")
    if W.TEXT_SHADOW == false and fs.SetShadowOffset then
        pcall(fs.SetShadowOffset, fs, 0, 0)
    end
    return fs
end

function W.SmallFont(parent, size)
    local fs = parent:CreateFontString(nil, "OVERLAY", "GameFontNormalSmall")
    if W.TEXT_SHADOW == false and fs.SetShadowOffset then
        pcall(fs.SetShadowOffset, fs, 0, 0)
    end
    if fs.GetFont then
        local ok, path, _, flags = pcall(fs.GetFont, fs)
        if ok and path then pcall(fs.SetFont, fs, path, size or 9, flags or "") end
    end
    return fs
end

-- A flat rounded panel. Pass an explicit {r,g,b,a} (or 4 numbers) to tint it,
-- otherwise it uses the L1 section colour. A 1px warm edge ring is drawn.
function W.Panel(parent, r, g, b, a)
    local f = CreateFrame("Frame", nil, parent)
    local color = (r or g or b) and { r, g, b, a or 1 } or W.Theme.panel
    W.Paint(f, color, 10, CARD_BORDER)
    return f
end

-- Four straight 1px lines, used for tiny controls (checkbox box, edit border).
function W.Border(f, r, g, b, a)
    local T = W.Theme
    r = r or T.border[1]; g = g or T.border[2]; b = b or T.border[3]
    a = a or 0.6
    local lines = {}
    for i = 1, 4 do
        local t = f:CreateTexture(nil, "ARTWORK")
        t:SetColorTexture(r, g, b, a)
        lines[i] = t
    end
    lines[1]:SetPoint("TOPLEFT", f, "TOPLEFT", 0, 0)
    lines[1]:SetPoint("TOPRIGHT", f, "TOPRIGHT", 0, 0)
    lines[1]:SetHeight(1)
    lines[2]:SetPoint("BOTTOMLEFT", f, "BOTTOMLEFT", 0, 0)
    lines[2]:SetPoint("BOTTOMRIGHT", f, "BOTTOMRIGHT", 0, 0)
    lines[2]:SetHeight(1)
    lines[3]:SetPoint("TOPLEFT", f, "TOPLEFT", 0, 0)
    lines[3]:SetPoint("BOTTOMLEFT", f, "BOTTOMLEFT", 0, 0)
    lines[3]:SetWidth(1)
    lines[4]:SetPoint("TOPRIGHT", f, "TOPRIGHT", 0, 0)
    lines[4]:SetPoint("BOTTOMRIGHT", f, "BOTTOMRIGHT", 0, 0)
    lines[4]:SetWidth(1)
    return lines
end

-- Thin 1px divider line.
function W.HLine(parent, y, pad, r, g, b, a)
    local T = W.Theme
    local d = parent:CreateTexture(nil, "ARTWORK")
    d:SetColorTexture(r or T.line[1], g or T.line[2], b or T.line[3], a or T.line[4])
    d:SetHeight(1)
    d:SetPoint("TOPLEFT", parent, "TOPLEFT", pad or 0, -y)
    d:SetPoint("TOPRIGHT", parent, "TOPRIGHT", -(pad or 0), -y)
