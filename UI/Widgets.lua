-- Blizzard's own DialogBox skin for the NPC companion panel. Uses the same textures
-- as QuestFrame / GossipFrame, not a look-alike dark panel (core game assets).
function W.SkinDialog(f)
    if f.SetBackdrop then
        pcall(f.SetBackdrop, f, {
            bgFile = DIALOG_BG, edgeFile = DIALOG_EDGE,
            tile = true, tileSize = 32, edgeSize = 16,
            insets = { left = 5, right = 5, top = 5, bottom = 5 },
        })
        pcall(f.SetBackdropColor, f, 1, 1, 1, 1)
        pcall(f.SetBackdropBorderColor, f, 1, 1, 1, 1)
        return f
    end
    solid(f, 0.09, 0.075, 0.055, 0.96)
    W.Border(f, 0.72, 0.58, 0.26, 0.9)
    return f
end

-- Native title bar: the fixed-size UI-DialogBox-Header texture (64px tall, anchored
-- 12px above the frame) is exactly what QuestFrame uses.
function W.DialogHeader(f, text, width)
    local bar = f:CreateTexture(nil, "ARTWORK")
    bar:SetTexture(DIALOG_HEADER)
    bar:SetSize(width or 256, 64)
    bar:SetPoint("TOP", f, "TOP", 0, 12)
    local t = f:CreateFontString(nil, "OVERLAY", "GameFontNormal")
    t:SetPoint("TOP", f, "TOP", 0, -2)
    t:SetText(text or "")
    f.headerBar = bar
    return t
end

-- Small rounded pill badge built from our own corner + white textures.
function W.Badge(parent, text, rgb, height)
    local T = W.Theme
    local c = rgb or T.accent
    local f = W.Frame(nil, parent)
    f:SetHeight(height or 15)
    f:SetWidth(60)
    -- accent ring + dim inset fill = a clean pill (no glow, no shadow)
    W.Paint(f, { c[1] * 0.18, c[2] * 0.18, c[3] * 0.18, 0.95 }, 7, { c[1], c[2], c[3], 0.9 })
    local fs = W.SmallFont(f, 9)
    fs:SetPoint("CENTER", f, "CENTER", 0, 0)
    fs:SetTextColor(c[1], c[2], c[3])
    function f:SetText(value)
        f.text = value or ""
        fs:SetText(f.text)
        local w = 48
        if fs.GetStringWidth then
            local ok, measured = pcall(fs.GetStringWidth, fs)
            if ok and measured then w = measured + 12 end
        end
        f:SetWidth(math.max(22, w))
    end
    f:SetText(text)
    return f
end

