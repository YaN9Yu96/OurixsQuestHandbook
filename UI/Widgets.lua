-- Flat rounded button. Hover = lighten; selected = warm tint + gold text.
-- Never a large gold fill.
function W.Button(parent, text, w, h)
    local T = W.Theme
    local b = CreateFrame("Button", nil, parent)
    b:SetSize(w or 160, h or 24)
    W.Paint(b, T.panelAlt, 8)
    local label = W.Font(b, "GameFontHighlightSmall")
    label:SetPoint("CENTER", b, "CENTER", 0, 0)
    label:SetText(text or "")
    label:SetTextColor(T.text[1], T.text[2], T.text[3])
    label:SetWordWrap(false)
    b.label = label
    b:SetScript("OnEnter", function()
        if not b.selected then W.Paint(b, T.rowHover, 8) end
    end)
    b:SetScript("OnLeave", function()
        if not b.selected then W.Paint(b, T.panelAlt, 8) end
    end)
    function b:SetSelected(on)
        b.selected = on and true or false
        if b.selected then
            W.Paint(b, T.rowSel, 8)
            label:SetTextColor(T.accent[1], T.accent[2], T.accent[3])
        else
            W.Paint(b, T.panelAlt, 8)
            label:SetTextColor(T.text[1], T.text[2], T.text[3])
        end
    end
    function b:SetLabel(text2)
        label:SetText(text2 or "")
    end
    return b
end

-- Modern pill toggle switch (PlateSCT-style approach, re-implemented). Label on the
-- left, a rounded track with a sliding knob on the right. Off = warm-gray track +
-- light knob; On = gold track + dark knob. A crisp two-state snap reads modern and
-- stays light. Active state is conveyed by the track colour, not a heavy glow.
function W.Toggle(parent, text, w, h)
    local T = W.Theme
    local b = CreateFrame("Button", nil, parent)
    b:SetSize(w or 160, h or 26)
    local label = W.Font(b, "GameFontHighlightSmall")
    label:SetPoint("LEFT", b, "LEFT", 0, 0)
    label:SetPoint("RIGHT", b, "RIGHT", -46, 0)
    label:SetJustifyH("LEFT")
    label:SetWordWrap(false)
    label:SetText(text or "")
    label:SetTextColor(T.text[1], T.text[2], T.text[3])
    b.label = label

    local sw = CreateFrame("Frame", nil, b)
    sw:SetSize(34, 18)
    sw:SetPoint("RIGHT", b, "RIGHT", 0, 0)
    W.Paint(sw, { 0.180, 0.157, 0.122 }, 9)
    b.swTrack = sw

    -- knob: a circle (a full-radius rounded rect inside a small frame)
    local knob = CreateFrame("Frame", nil, sw)
    knob:SetSize(14, 14)
    knob:SetPoint("LEFT", sw, "LEFT", 2, 0)
    W.Paint(knob, { 0.639, 0.604, 0.541 }, 7)
    b.knob = knob
    b.selected = false

    local function Paint()
        if b.selected then
            W.Tint(sw, ACCENT)
            W.Tint(knob, { 0.071, 0.063, 0.051 })
            knob:ClearAllPoints(); knob:SetPoint("RIGHT", sw, "RIGHT", -2, 0)
            label:SetTextColor(T.accent[1], T.accent[2], T.accent[3])
        else
            W.Tint(sw, { 0.180, 0.157, 0.122 })
            W.Tint(knob, { 0.639, 0.604, 0.541 })
            knob:ClearAllPoints(); knob:SetPoint("LEFT", sw, "LEFT", 2, 0)
            label:SetTextColor(T.text[1], T.text[2], T.text[3])
        end
    end
    function b:SetSelected(on)
        b.selected = on and true or false
        Paint()
    end
    function b:SetLabel(t) label:SetText(t or "") end
    Paint()
    return b
end

-- Two-segment switch (Alliance / Horde). One outlined track split into two halves; each
-- half is its own frame carrying both its fill and its label, because a child frame
-- always paints over the parent's font strings (a sliding pill on the button itself
-- would have covered the labels). Active half = warm tint + gold text, idle half = flat
-- + muted text. Clicking a half reports through `OnSelect(index)`.
function W.Segment(parent, textA, textB, w, h)
    local T = W.Theme
    w, h = w or 112, h or 22
    local b = CreateFrame("Button", nil, parent)
    b:SetSize(w, h)
    W.Paint(b, T.panelAlt, 8, CARD_BORDER)

    local halfW = math.max(1, (w - 4) * 0.5)
    local function makeHalf(text, side, offset)
        local f = CreateFrame("Frame", nil, b)
        f:SetSize(halfW, math.max(1, h - 4))
        f:SetPoint(side, b, side, offset, 0)
        W.Paint(f, T.panelAlt, 6)
        local label = W.Font(f, "GameFontHighlightSmall")
        label:SetPoint("CENTER", f, "CENTER", 0, 0)
        label:SetText(text or "")
        label:SetWordWrap(false)
        return f, label
    end
    local halfA, labelA = makeHalf(textA, "LEFT", 2)
    local halfB, labelB = makeHalf(textB, "RIGHT", -2)
    b.halfA, b.halfB = halfA, halfB
    b.index = 1

    local function Repaint()
        local onF, onT, offF, offT
        if b.index == 1 then
            onF, onT, offF, offT = halfA, labelA, halfB, labelB
        else
            onF, onT, offF, offT = halfB, labelB, halfA, labelA
        end
        W.Tint(onF, T.rowSel)
        onT:SetTextColor(T.accent[1], T.accent[2], T.accent[3])
        W.Tint(offF, T.panelAlt)
        offT:SetTextColor(T.muted[1], T.muted[2], T.muted[3])
    end
    function b:SetIndex(i)
        b.index = (i == 2) and 2 or 1
        Repaint()
    end
    b:SetScript("OnClick", function()
        local scale = b:GetEffectiveScale()
        if not scale or scale == 0 then scale = 1 end
        local cx = select(1, GetCursorPosition()) / scale
        local left = b:GetLeft() or cx
        local i = (cx - left) < (b:GetWidth() * 0.5) and 1 or 2
        if i ~= b.index then
            b:SetIndex(i)
            if b.OnSelect then b.OnSelect(i) end
        end
    end)
    Repaint()
    return b
end

function W.EditBox(parent, w, h)
    local T = W.Theme
    local box = CreateFrame("EditBox", nil, parent)
    box:SetSize(w or 180, h or 22)
    box:SetAutoFocus(false)
    box:SetFontObject("GameFontHighlight")
    if W.TEXT_SHADOW == false and box.SetShadowOffset then
        pcall(box.SetShadowOffset, box, 0, 0)
    end
    box:SetTextInsets(8, 8, 0, 0)
    box:SetJustifyH("LEFT")
    W.Paint(box, L2, 8, CARD_BORDER)
    box:SetScript("OnEscapePressed", function() box:ClearFocus() end)
    box:SetScript("OnEditFocusGained", function()
        W.Paint(box, Blend(L2, ACCENT, 0.30), 8, T.accent)
    end)
    box:SetScript("OnEditFocusLost", function()
        W.Paint(box, L2, 8, CARD_BORDER)
    end)
    return box
end

-- Scrollable frame with a rounded, draggable, click-to-page thumb. The thumb is a
-- child of the *parent* panel (not the scrollframe) so it stays put, and is moved by
-- UpdateThumb. No visible track needed; the thin pill reads as a scrollbar.
function W.Scroll(parent)
    local T = W.Theme
    local sf = CreateFrame("ScrollFrame", nil, parent)
    sf:EnableMouseWheel(true)
    local child = CreateFrame("Frame", nil, sf)
    child:SetWidth(200)
    sf:SetScrollChild(child)
    sf.child = child

    -- Normal width is thin; the hover highlight only changes colour, never width, so
    -- the bar keeps a constant footprint whether or not the cursor is over it.
    local IDLE_W, HOVER_W = 4, 4
    local IDLE_C = Blend(T.line, ACCENT, 0.30)
    local HOVER_C = Blend(T.line, ACCENT, 0.85)

    -- The thumb has to sit ABOVE the pooled rows/cards that live inside the scroll
    -- child: those are separate frames, and if any of them is above the thumb the
    -- mouse lands on the row and the bar never receives OnEnter (this is why the
    -- highlight "did nothing" even though the script was correct). A fixed high
    -- frame level relative to the panel guarantees the bar stays on top.
    local thumb = CreateFrame("Button", nil, parent)
    thumb:SetFrameLevel((parent:GetFrameLevel() or 1) + 40)
    thumb:SetWidth(IDLE_W)
    W.Paint(thumb, IDLE_C, 3)
    sf.thumb = thumb

    -- Hover state, driven from OnUpdate by IsMouseOver as well as by OnEnter/OnLeave.
    -- Polling keeps it working even when another frame would otherwise swallow the
    -- enter/leave events.
    local hover, drag = false, false
    local function SetHover(on)
        on = on and true or false
        if hover == on then return end
        hover = on
        thumb:SetWidth(on and HOVER_W or IDLE_W)
        W.Tint(thumb, on and HOVER_C or IDLE_C)
    end
    thumb:SetScript("OnEnter", function() SetHover(true) end)
    thumb:SetScript("OnLeave", function() if not drag then SetHover(false) end end)

    local startCursor, startScroll = 0, 0
    local function uiScale() return UIParent and UIParent:GetEffectiveScale() or 1 end
    local function cursorUI()
        local x, y = GetCursorPosition()
        local s = uiScale()
        if not s or s == 0 then s = 1 end
        return x / s, y / s
    end

    local function UpdateThumb()
        local ch = child:GetHeight() or 0
        local vh = sf:GetHeight() or 0
        local max = math.max(0, ch - vh)
        if max <= 0 or vh <= 0 then
            thumb:Hide()
            SetHover(false)
            return
        end
        thumb:Show()
        local th = math.max(24, math.min(vh, vh * vh / math.max(1, ch)))
        local span = math.max(0, vh - th)
        local frac = (sf:GetVerticalScroll() or 0) / max
        thumb:ClearAllPoints()
        thumb:SetHeight(th)
        thumb:SetPoint("TOPRIGHT", sf, "TOPRIGHT", -3, -3 - frac * span)
    end
    sf.UpdateThumb = UpdateThumb

    -- Drag: plain mouse-down capture + OnUpdate. RegisterForDrag is deliberately not
    -- used, so releasing the button outside the bar still ends the drag cleanly.
    thumb:SetScript("OnMouseDown", function(_, button)
        if button ~= "LeftButton" then return end
        drag = true
        SetHover(true)
        startCursor = select(2, cursorUI())
        startScroll = sf:GetVerticalScroll() or 0
    end)
    thumb:SetScript("OnMouseUp", function() drag = false end)
    thumb:SetScript("OnHide", function() drag = false end)

    sf:SetScript("OnUpdate", function()
        if thumb:IsShown() and thumb.IsMouseOver then
            local over = thumb:IsMouseOver(0, 0, 0, 0)
            if over and not hover then SetHover(true) end
            if not over and hover and not drag then SetHover(false) end
        end
        if not drag then return end
        if not IsMouseButtonDown("LeftButton") then
            drag = false
            if not (thumb:IsShown() and thumb:IsMouseOver(0, 0, 0, 0)) then SetHover(false) end
            return
        end
        local _, y = cursorUI()
        local max = math.max(0, (child:GetHeight() or 0) - (sf:GetHeight() or 0))
        local span = math.max(1, (sf:GetHeight() or 0) - (thumb:GetHeight() or 0))
        local delta = (y - startCursor)            -- up = positive
        sf:SetVerticalScroll(math.max(0, math.min(max, startScroll - delta * (max / span))))
        UpdateThumb()
    end)

    -- Click on the scroll area pages by a viewport.
    sf:SetScript("OnMouseDown", function(_, button)
        if button ~= "LeftButton" or drag then return end
        local _, cy = cursorUI()
        local top = sf:GetTop() or 0
        local bottom = sf:GetBottom() or 0
        local rel = top > bottom and (top - cy) / (top - bottom) or 0
        local max = math.max(0, (child:GetHeight() or 0) - (sf:GetHeight() or 0))
        sf:SetVerticalScroll(math.max(0, math.min(max, rel * max)))
        UpdateThumb()
    end)

    sf:SetScript("OnVerticalScroll", UpdateThumb)
    sf:SetScript("OnSizeChanged", UpdateThumb)
    sf:SetScript("OnMouseWheel", function(self, delta)
        local max = math.max(0, (child:GetHeight() or 0) - (self:GetHeight() or 0))
        local cur = self:GetVerticalScroll() or 0
        self:SetVerticalScroll(math.max(0, math.min(max, cur - delta * 46)))
        UpdateThumb()
    end)
    return sf
end

