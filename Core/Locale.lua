local locale = (GetLocale and GetLocale()) or "enUS"
local t = STRINGS[locale]
if not t then
    -- esMX reuses esES, ptBR is explicit, enGB falls through to the English keys.
    local lang = locale:sub(1, 2)
    for k, v in pairs(STRINGS) do
        if k:sub(1, 2) == lang then t = v break end
    end
end
t = t or {}

ns.L = setmetatable({}, { __index = function(_, k) return t[k] or k end })
ns.locale = locale

function ns.IsChineseClient()
    return locale == "zhCN" or locale == "zhTW"
end

